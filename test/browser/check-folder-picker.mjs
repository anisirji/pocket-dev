    assert.ok(requests.at(-1).startsWith(`${a.base}/m/${b.id}/api/folders/browse`));
    const geometry = await picker.evaluate((d) => ({ width: d.getBoundingClientRect().width, height: d.clientHeight, listing: d.querySelector('.fp-list').clientHeight }));
    assert.ok(width < 760 ? geometry.width === width : geometry.width >= 640);
    assert.ok(geometry.listing > geometry.height * .5, JSON.stringify(geometry));
    assert.equal(await picker.locator('.fp-selected').count(), 0);
    assert.equal(await picker.getByRole('button', { name: 'New folder', exact: true }).isVisible(), false);
    await picker.locator('.fp-row').first().focus(); await page.keyboard.press('ArrowDown');
    assert.equal(await picker.locator('.fp-row').nth(1).evaluate((row) => row === document.activeElement), true);
    await page.keyboard.press('Escape'); await picker.waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#emptyOpenFolder').evaluate((button) => button === document.activeElement), true);
    await page.waitForFunction(() => !history.state?.fpPicker);
    await page.locator('#emptyOpenFolder').click();
    await browseHome();
    await page.evaluate(() => history.back()); await picker.waitFor({ state: 'hidden' });
    await page.locator('#emptyOpenFolder').click();
    await browseHome();
    await picker.getByLabel('Search folders', { exact: true }).fill('Project B');
    await page.waitForFunction(() => document.querySelectorAll('dialog[open] .fp-row').length === 1);
    assert.equal(await picker.locator('.fp-row').count(), 1);
    await picker.getByLabel('Search folders', { exact: true }).fill('');
    await picker.getByRole('button', { name: 'Open folder AstraTech', exact: true }).waitFor();
    await picker.getByRole('button', { name: 'Folder options', exact: true }).click();
    await picker.getByLabel('Show hidden folders', { exact: true }).check();
    await page.keyboard.press('Escape');
    await picker.getByRole('button', { name: 'Open folder .hidden-project', exact: true }).waitFor();
    await picker.getByRole('button', { name: 'Folder options', exact: true }).click();
    await picker.getByLabel('Sort folders by').selectOption('modified:desc'); await pause(150);
    assert.equal(new URL(requests.at(-1)).searchParams.get('order'), 'desc');
    await page.keyboard.press('Escape');
    await picker.getByRole('button', { name: 'Folder options', exact: true }).click();
    await picker.getByRole('button', { name: 'New folder', exact: true }).click();
    await picker.getByLabel('New item name').fill(`Fresh ${width}`);
    await picker.locator('.fp-newform').getByRole('button', { name: 'Create', exact: true }).click();
    await page.waitForFunction((name) => document.querySelector('dialog[open] [aria-current]')?.textContent === name, `Fresh ${width}`);
    assert.ok(fs.existsSync(path.join(b.home, `Fresh ${width}`))); assert.ok(!fs.existsSync(path.join(a.home, `Fresh ${width}`)));
    await picker.getByRole('button', { name: 'Up', exact: true }).click();
    await picker.getByRole('button', { name: 'Folder options', exact: true }).click();
    await picker.getByRole('button', { name: 'Go to path', exact: true }).click();
    await picker.getByLabel('Go to path', { exact: true }).fill(projectB);
    await picker.locator('.fp-pathform').getByRole('button', { name: 'Go', exact: true }).click();
    await page.waitForFunction((path) => document.querySelector('dialog[open] [aria-current]')?.title === path, projectB);
    await picker.getByRole('button', { name: 'Folder options', exact: true }).click();
    await picker.getByRole('button', { name: 'Copy path', exact: true }).click();
    await picker.getByRole('status').filter({ hasText: 'Path copied.' }).waitFor();
    await picker.getByRole('button', { name: 'Up', exact: true }).click();
