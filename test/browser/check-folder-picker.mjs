    assert.equal((await picker.locator('.fp-footer').boundingBox()).y, footer.y);
    await picker.locator('.fp-list').evaluate((list) => { list.scrollTop = 0; });
    await picker.screenshot({ path: `/tmp/pocket-dev-folder-picker-${width}.png` });
    await page.evaluate(() => { const s = document.documentElement.style; s.setProperty('--bg', 'oklch(.98 .006 267)'); s.setProperty('--panel', 'oklch(.95 .008 267)'); s.setProperty('--panel-2', 'oklch(.92 .01 267)'); s.setProperty('--text', 'oklch(.22 .025 267)'); s.setProperty('--line', 'oklch(.84 .015 267)'); s.setProperty('--muted', 'oklch(.48 .025 267)'); s.setProperty('--accent', 'oklch(.55 .18 255)'); s.colorScheme = 'light'; });
    assert.equal(await picker.evaluate((d) => getComputedStyle(d).colorScheme), 'light');
    await picker.screenshot({ path: `/tmp/pocket-dev-folder-picker-light-${width}.png` });
    await page.evaluate(() => { document.documentElement.removeAttribute('style'); });
    await picker.getByLabel('Search folders', { exact: true }).fill('Project B');
    await picker.getByRole('button', { name: 'Open folder Project B', exact: true }).click();
    await picker.getByRole('button', { name: 'Open folder', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#projectName').textContent === 'Project B');
