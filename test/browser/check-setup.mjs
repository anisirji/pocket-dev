// Real isolated Mac Admin server. Installer mutations and OS permission prompts are never executed.
import assert from 'node:assert/strict';
import { startServer, until } from '../helpers/server.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const cleanups = [], t = { after: (fn) => cleanups.push(fn) };
let browser;
try {
  const server = await startServer(t), login = await server.login();
  assert.equal((await server.request('POST', '/api/setup/actions', { cookie: login.cookie, body: { tool: 'codex', confirmed: true, requestId: 'phone-must-not-install' } })).status, 404);
  assert.equal((await server.request('GET', '/api/setup/plan', { adminRequest: true, headers: { 'x-forwarded-for': '203.0.113.5' } })).status, 403);
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } }), page = await context.newPage(), errors = [], installs = [];
  page.on('pageerror', (error) => errors.push(String(error)));
  await page.route('**/api/permissions', (route) => route.fulfill({ json: { items: [{ id: 'screen', title: 'Screen Recording', group: 'mac', state: 'granted', why: 'Fixture permission' }], setup: null } }));
  await page.route('**/api/setup/plan', async (route) => {
    const response = await route.fetch(), data = await response.json();
    data.tools.find((tool) => tool.id === 'codex').install = { action: 'run', command: 'npm install -g @openai/codex' };
    await route.fulfill({ json: data });
  });
  await page.route('**/api/setup/actions', async (route) => { installs.push(route.request().postDataJSON()); await route.fulfill({ status: 409, json: { error: 'Fixture installer unavailable. Check setup again.' } }); });
  await page.goto(server.admin);
  const dialog = page.locator('#setup'); await dialog.waitFor({ state: 'visible' });
  assert.match(await dialog.innerText(), /Welcome to Pocket Dev/);
  assert.equal(installs.length, 0);
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByText('Tools on this computer', { exact: true }).waitFor();
  await dialog.locator('.setup-tool').first().waitFor();
  const actions = await dialog.locator('#setupActions').boundingBox();
  assert.ok(actions.x >= 0 && actions.x + actions.width <= 390 && actions.y + actions.height <= 844, 'all setup actions fit on the phone');
  await page.screenshot({ path: '/tmp/pocket-setup-mobile.png' });
  assert.equal(installs.length, 0, 'opening tool inspection never installs anything');
  const codex = dialog.locator('.setup-tool').filter({ has: page.getByText('Codex', { exact: true }) });
  await codex.getByRole('button', { name: 'Install', exact: true }).click();
  await until(async () => (await dialog.locator('#setupStatus').innerText()).includes('Fixture installer unavailable'));
  assert.deepEqual(Object.keys(installs[0]).sort(), ['confirmed', 'requestId', 'tool']);
  assert.equal(installs[0].confirmed, true); assert.equal(installs[0].tool, 'codex');
  await dialog.getByRole('button', { name: 'Pause setup', exact: true }).click(); await dialog.waitFor({ state: 'hidden' });
  assert.equal((await server.local('GET', '/api/state')).data.setup.step, 2);
  await page.reload(); assert.equal(await dialog.isVisible(), false, 'paused setup never reopens itself');
  await page.locator('#nav [data-group="computer"]').click();
  await page.locator('#permSetup').click();
  await dialog.getByText('Tools on this computer', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByRole('button', { name: 'Show login QR', exact: true }).click();
  await dialog.getByAltText('One-time Pocket Dev login QR', { exact: true }).waitFor();
  assert.match(await dialog.innerText(), /Works once. Expires at/);
  await dialog.getByLabel('New setup password', { exact: true }).fill('fixture-new-password');
  await dialog.getByLabel('Confirm setup password', { exact: true }).fill('fixture-new-password');
  await dialog.getByRole('button', { name: 'Set password', exact: true }).click();
  await until(async () => (await dialog.locator('#setupStatus').innerText()) === 'Password saved.');
  assert.equal(await dialog.getByLabel('New setup password', { exact: true }).inputValue(), '');
  assert.equal((await server.request('GET', '/api/status', { cookie: login.cookie })).data.status, 'active', 'changing the password preserves existing device sessions');
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByRole('button', { name: 'Done', exact: true }).click(); await dialog.waitFor({ state: 'hidden' });
  assert.equal((await server.local('GET', '/api/state')).data.setup.complete, true);
  await page.reload(); assert.equal(await dialog.isVisible(), false, 'completed setup retains the existing completion marker');
  await page.setViewportSize({ width: 1280, height: 900 }); await page.locator('#permSetup').click();
  await dialog.getByRole('button', { name: 'Done', exact: true }).waitFor();
  assert.equal(installs.length, 1, 'resume, reload and completion never replay installations');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('PASS Mac graphical setup, explicit install errors, pause/resume, one-time QR, password/session preservation and completion without OS prompts or installations');
  await context.close();
} finally { await browser?.close(); for (const cleanup of cleanups.reverse()) await cleanup(); }
