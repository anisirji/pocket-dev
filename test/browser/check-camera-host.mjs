// A real isolated Pocket Dev server and browser camera pipeline. Uses a synthetic browser camera.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import WebSocket from 'ws';
import { startServer, until } from '../helpers/server.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'browser-camera-e2e-'));
const record = path.join(root, 'host-url');
const cleanup = [];
let browser;
try {
  const s = await startServer({ after: (fn) => cleanup.unshift(fn) }, { env: { POCKET_DEV_CAMERA_HOST_RECORD: record } });
  fs.writeFileSync(s.config, JSON.stringify({ ...JSON.parse(fs.readFileSync(s.config, 'utf8')), cameraIceServers: [] }));
  const { cookie } = await s.login();
  browser = await chromium.launch({ headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'],
    ...(process.env.CHROME_PATH && { executablePath: process.env.CHROME_PATH }) });
  const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await phoneContext.addInitScript(() => {
    const Native = window.RTCPeerConnection;
    window.__cameraPeers = [];
    window.RTCPeerConnection = class extends Native { constructor(...args) { super(...args); window.__cameraPeers.push(this); } };
    window.__CameraPeerFactory = window.RTCPeerConnection;
    window.__cameraFrames = 0; window.__cameraFramePolls = 0;
    const NativeSocket = window.WebSocket;
    window.WebSocket = class extends NativeSocket {
      constructor(...args) { super(...args); if (String(args[0]).includes('/ws/camera-view')) this.addEventListener('message', (event) => { if (typeof event.data !== 'string') window.__cameraFrames++; }); }
    };
    const fetch = window.fetch;
    window.fetch = (...args) => { if (String(args[0]).includes('/api/camera/frame')) window.__cameraFramePolls++; return fetch(...args); };
  });
  const split = cookie.indexOf('=');
  await phoneContext.addCookies([{ name: cookie.slice(0, split), value: cookie.slice(split + 1), url: s.base }]);
  const phone = await phoneContext.newPage();
  const errors = [];
  phone.on('pageerror', (err) => errors.push(err.message));
  await phone.goto(s.base);
  await phone.waitForFunction(() => typeof window.openCameraSheet === 'function');
  await phone.evaluate(() => window.openCameraSheet());
  await phone.waitForFunction(() => !document.querySelector('.camera-controls .start').disabled);
  const closeBounds = await phone.getByRole('button', { name: 'Close', exact: true }).boundingBox();
  const statusBounds = await phone.locator('#macStatus').boundingBox();
  assert.ok(!statusBounds || closeBounds.y >= statusBounds.y + statusBounds.height, 'the status strip does not cover the camera title or Close button');
  assert.equal(fs.existsSync(record), false, 'opening the viewer never starts a PC camera tab');
  assert.equal((await s.request('GET', '/api/camera/support', { cookie })).data.captureMethod, 'browser');
  const startPhone = async () => phone.getByRole('button', { name: 'Start camera', exact: true }).click();
  await phone.getByRole('button', { name: 'Close', exact: true }).click();
  await s.local('POST', '/api/permissions/setup', { status: 'skipped' });
  const admin = await browser.newPage();
  await admin.goto(s.admin + '/#camera');
  await admin.getByRole('button', { name: 'Prepare remote camera', exact: true }).click();
  await until(() => fs.existsSync(record));
  const hostContext = await browser.newContext({ permissions: ['camera'], viewport: { width: 1080, height: 800 } });
  let host = await hostContext.newPage();
  host.on('pageerror', (err) => errors.push(err.message));
  const setupUrl = fs.readFileSync(record, 'utf8');
  await host.goto(setupUrl);
  await admin.getByText('Camera verified', { exact: true }).waitFor();
  await host.waitForFunction(() => document.getElementById('preview').srcObject === null);
  assert.ok(JSON.parse(fs.readFileSync(s.config, 'utf8')).cameraSetup.verifiedAt, 'one-time setup verification is saved');
  await host.close();
  await phone.evaluate(() => window.openCameraSheet());
  await phone.waitForFunction(() => document.querySelector('.camera-status').textContent.includes('Ready for remote'));
  await startPhone();
  await until(() => fs.readFileSync(record, 'utf8') !== setupUrl);
  const firstHostUrl = fs.readFileSync(record, 'utf8');
  host = await hostContext.newPage();
  await host.goto(firstHostUrl);
  await phone.waitForFunction(() => document.querySelector('.camera-status').textContent.includes('Live'));
  await host.waitForFunction(() => document.getElementById('state').textContent === 'Camera on');
  await phone.waitForFunction(() => document.querySelector('.camera-sheet').dataset.streamTransport === 'rtc', null, { timeout: 12000 });
  const decoded = () => phone.evaluate(async () => {
    const peer = window.__cameraPeers.at(-1);
    const report = [...(await peer.getStats()).values()].find((entry) => entry.type === 'inbound-rtp' && entry.kind === 'video');
    return { frames: report?.framesDecoded || 0, at: performance.now() };
  });
  // Negotiation can finish before the decoder starts, especially on hosted runners.
  // Measure sustained playback after actual frames arrive, without counting startup delay.
  await until(async () => (await decoded()).frames >= 5, 15000);
  const before = await decoded();
  await phone.waitForTimeout(3000);
  const after = await decoded();
  const fps = (after.frames - before.frames) * 1000 / (after.at - before.at);
  assert.ok(fps >= 15, `native video should decode at least 15 FPS, got ${fps.toFixed(1)}`);
  console.log(`Measured native video: ${fps.toFixed(1)} decoded frames per second.`);
  assert.equal(await host.evaluate(() => document.getElementById('preview').srcObject.getAudioTracks().length), 0);
  assert.equal(await phone.locator('.camera-video').evaluate((video) => video.videoWidth > 0), true);
  const downloadPromise = phone.waitForEvent('download');
  await phone.getByRole('button', { name: 'Snapshot', exact: true }).click();
  const snapshot = fs.readFileSync(await (await downloadPromise).path());
  assert.equal(snapshot[0], 255); assert.equal(snapshot[1], 216);
  assert.ok(snapshot.length > 1000, 'a real JPEG travelled from the PC browser to the phone download');
  await phone.waitForTimeout(31_000);
  assert.equal(await host.locator('#state').textContent(), 'Camera on', 'the PC capture survives the server heartbeat');
  assert.equal(await phone.locator('.camera-error').isHidden(), true);
  assert.match(await phone.locator('.camera-status').textContent(), /Live/);
  assert.equal(await phone.evaluate(() => window.__cameraFramePolls), 0, 'streaming never waits on individual HTTP image requests');
  await host.screenshot({ path: '/tmp/pocket-dev-camera-browser-host.png' });
  await phone.screenshot({ path: '/tmp/pocket-dev-camera-browser-phone.png' });
  await phone.getByRole('button', { name: 'Stop', exact: true }).click();
  await host.waitForFunction(() => document.getElementById('preview').srcObject === null);
  await phone.evaluate(() => { window.RTCPeerConnection = undefined; });
  await startPhone();
  await phone.waitForFunction(() => document.querySelector('.camera-sheet').dataset.streamTransport === 'relay' && !document.querySelector('.camera-image').hidden);
  const relayBefore = await phone.evaluate(() => ({ frames: window.__cameraFrames, at: performance.now() }));
  await phone.waitForTimeout(3000);
  const relayAfter = await phone.evaluate(() => ({ frames: window.__cameraFrames, at: performance.now() }));
  const relayFps = (relayAfter.frames - relayBefore.frames) * 1000 / (relayAfter.at - relayBefore.at);
  assert.ok(relayFps >= 8, `fallback should push at least 8 FPS, got ${relayFps.toFixed(1)}`);
  assert.equal(await phone.evaluate(() => window.__cameraFramePolls), 0);
  console.log(`Measured pushed-image fallback: ${relayFps.toFixed(1)} frames per second, no frame polling.`);
  await phone.getByRole('button', { name: 'Stop', exact: true }).click();
  await host.waitForFunction(() => document.getElementById('preview').srcObject === null);
  await phone.evaluate(() => { window.RTCPeerConnection = window.__CameraPeerFactory; });
  await startPhone();
  await phone.waitForFunction(() => document.querySelector('.camera-status').textContent.includes('Live'));
  assert.equal(fs.readFileSync(record, 'utf8'), firstHostUrl, 'restarting reuses the existing browser tab');
  await host.getByRole('button', { name: 'Stop camera', exact: true }).click();
  await phone.waitForFunction(() => !document.querySelector('.camera-controls .start').disabled && document.querySelector('.camera-image').hidden);
  await startPhone();
  await phone.waitForFunction(() => document.querySelector('.camera-status').textContent.includes('Live'));
  await host.close();
  await phone.waitForFunction(() => document.querySelector('.camera-image').hidden && !document.querySelector('.camera-controls .start').disabled);
  await startPhone();
  await until(() => fs.readFileSync(record, 'utf8') !== firstHostUrl);
  host = await hostContext.newPage();
  await host.addInitScript(() => { navigator.mediaDevices.getUserMedia = async () => { throw new DOMException('Blocked', 'NotAllowedError'); }; });
  await host.goto(fs.readFileSync(record, 'utf8'));
  await phone.getByRole('alert').filter({ hasText: 'Camera access was blocked' }).waitFor();
  assert.equal(await host.locator('#preview').evaluate((video) => video.srcObject === null), true);

  assert.equal((await s.request('GET', '/camera-host.html', { headers: { 'x-forwarded-for': '192.0.2.1' } })).status, 403);
  const refused = new WebSocket(s.base.replace('http', 'ws') + '/ws/camera-host?token=' + '0'.repeat(64), { headers: { origin: s.base } });
  await new Promise((resolve, reject) => { refused.on('open', () => reject(new Error('wrong host token accepted'))); refused.on('error', () => resolve()); });
  assert.deepEqual(errors, []);
  console.log('Browser-camera end-to-end checks passed: unattended start, native video FPS, pushed fallback FPS, no HTTP polling, snapshots, heartbeat, Stop, permissions, and source authentication.');
} finally {
  await browser?.close();
  for (const fn of cleanup) await fn();
  fs.rmSync(root, { recursive: true, force: true });
}
