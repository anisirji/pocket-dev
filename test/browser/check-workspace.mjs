// Real server, local browser editor and real PTY sessions. AI commands are harmless fixture binaries.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { startServer } from '../helpers/server.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'pocket-workspace-check-'));
const cleanup = [];
let browser;
try {
  const bin = path.join(temp, 'bin'); fs.mkdirSync(bin);
  for (const tool of ['codex', 'claude']) fs.writeFileSync(path.join(bin, tool), `#!/bin/sh\necho '${tool} fixture ready'\nexec /bin/cat\n`, { mode: 0o755 });
  const shell = path.join(bin, 'workspace-shell');
  fs.writeFileSync(shell, '#!/bin/sh\nexport PATH="$POCKET_DEV_WORKSPACE_FAKE_BIN:$PATH"\nexec /bin/bash --noprofile --norc\n', { mode: 0o755 });
  const server = await startServer({ after(fn) { cleanup.unshift(fn); } }, { env: { PATH: bin + path.delimiter + process.env.PATH, SHELL: shell, POCKET_DEV_WORKSPACE_FAKE_BIN: bin } });
  const project = path.join(server.home, 'workspace-project'); fs.mkdirSync(project);
  fs.mkdirSync(path.join(project, 'src'));
  const file = path.join(project, 'src', 'app.js'); fs.writeFileSync(file, '\ufeffconst greeting = "hello";\r\n');
  fs.writeFileSync(path.join(project, 'README.md'), '# Workspace fixture\n');
  const { cookie } = await server.login();
  browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH && { executablePath: process.env.CHROME_PATH }) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
  const equals = cookie.indexOf('=');
  await context.addCookies([{ name: cookie.slice(0, equals), value: cookie.slice(equals + 1), url: server.base }]);
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', (failure) => errors.push(failure.message));
  await page.goto(server.base + '/workspace.html');
  await page.locator('#emptyOpenFolder').click();
  await page.getByRole('button', { name: 'Open folder workspace-project', exact: true }).click();
  await page.locator('#folderPicker .fp-footer .fp-primary').click();
  await page.getByRole('button', { name: 'Folder src', exact: true }).click();
  await page.getByRole('button', { name: 'File app.js', exact: true }).click();
  const content = page.locator('.cm-content');
  await content.click(); await page.keyboard.press('ControlOrMeta+End'); await page.keyboard.insertText('// saved from the workspace\n');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#workspaceStatus').textContent === 'Saved app.js');
  assert.match(fs.readFileSync(file, 'utf8'), /saved from the workspace/);
  assert.ok(fs.readFileSync(file, 'utf8').startsWith('\ufeff'), 'UTF-8 BOM is preserved');
  assert.equal(/(?<!\r)\n/.test(fs.readFileSync(file, 'utf8')), false, 'Windows line endings are preserved');
  await page.getByRole('button', { name: 'File README.md', exact: true }).click();
  await page.getByRole('button', { name: 'Open app.js', exact: true }).click();
  assert.match(await content.textContent(), /saved from the workspace/);
  // A concurrent agent edit is never silently overwritten.
  await content.click(); await page.keyboard.press('ControlOrMeta+End'); await page.keyboard.insertText('// local unsaved\n');
  fs.writeFileSync(file, '// changed by the agent\n');
  await page.keyboard.press('ControlOrMeta+s');
  await page.getByRole('alert').filter({ hasText: 'changed on the computer' }).waitFor();
  assert.equal(fs.readFileSync(file, 'utf8'), '// changed by the agent\n');
  assert.match(await content.textContent(), /local unsaved/);
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: 'Reload file', exact: false }).click();
  await page.waitForFunction(() => document.querySelector('.cm-content').textContent.includes('changed by the agent'));
  await page.getByRole('button', { name: 'New file', exact: true }).click();
  await page.locator('#newEntryName').fill('notes.txt'); await page.locator('#newEntryForm button[type=submit]').click();
  await page.getByRole('button', { name: 'Open notes.txt', exact: true }).waitFor();
  assert.equal(fs.existsSync(path.join(project, 'notes.txt')), true);
  await page.locator('#uploadPicker').setInputFiles({ name: 'uploaded.txt', mimeType: 'text/plain', buffer: Buffer.from('Uploaded from workspace') });
  await page.getByRole('button', { name: 'File uploaded.txt', exact: true }).waitFor();
  assert.equal(fs.readFileSync(path.join(project, 'uploaded.txt'), 'utf8'), 'Uploaded from workspace');
  await page.locator('#fileFilter').fill('README');
  await page.locator('#fileTree').getByRole('button', { name: 'README.md', exact: true }).waitFor();
  await page.locator('#fileFilter').fill('');
  await page.getByRole('button', { name: 'File notes.txt', exact: true }).waitFor();
  const width = await page.locator('.ws-explorer').evaluate((node) => node.getBoundingClientRect().width);
  await page.getByRole('separator', { name: 'Resize explorer' }).focus(); await page.keyboard.press('ArrowRight');
  assert.ok(await page.locator('.ws-explorer').evaluate((node) => node.getBoundingClientRect().width) > width);
  const frame = page.frameLocator('#toolsFrame');
  await page.getByRole('button', { name: 'New project terminal', exact: false }).click();
  await page.waitForFunction(() => document.querySelector('#workspaceStatus').textContent === 'Terminal · workspace-project');
  await frame.locator('#cmd').fill('printf WORKSPACE_TERMINAL_OK'); await frame.locator('#send').click();
  await frame.locator('.term.active').filter({ hasText: 'WORKSPACE_TERMINAL_OK' }).waitFor();
  const projectSessions = (await server.request('GET', '/api/sessions', { cookie })).data.filter((session) => session.cwd === fs.realpathSync(project));
  assert.ok(projectSessions.length > 0, 'workspace terminals start in the selected project');
  await page.locator('#terminalOptions').click(); await page.getByRole('button', { name: 'Codex terminal', exact: true }).click();
  await frame.locator('.term.active').filter({ hasText: 'codex fixture ready' }).waitFor();
  await page.locator('#terminalOptions').click(); await page.getByRole('button', { name: 'Claude terminal', exact: true }).click();
  await frame.locator('.term.active').filter({ hasText: 'claude fixture ready' }).waitFor();
  const count = (await server.request('GET', '/api/sessions', { cookie })).data.length;
  await page.locator('#terminalOptions').click(); await page.getByRole('button', { name: 'Codex terminal', exact: true }).click();
  await frame.locator('.term.active').filter({ hasText: 'codex fixture ready' }).waitFor();
  assert.equal((await server.request('GET', '/api/sessions', { cookie })).data.length, count, 'AI tabs reuse their running project sessions');
  await page.getByRole('button', { name: 'File README.md', exact: true }).click();
  await page.screenshot({ path: '/tmp/pocket-dev-workspace-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Files', exact: true }).click();
  await page.getByRole('button', { name: 'File notes.txt', exact: true }).click();
  await content.click(); await page.keyboard.insertText('Mobile draft');
  await page.locator('.ws-mobile').getByRole('button', { name: 'Terminal', exact: true }).click();
  await page.getByRole('button', { name: 'Editor', exact: true }).click();
  assert.match(await content.textContent(), /Mobile draft/);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#workspaceStatus').textContent === 'Saved notes.txt');
  assert.equal(fs.readFileSync(path.join(project, 'notes.txt'), 'utf8'), 'Mobile draft');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'phone layout has no horizontal page overflow');
  await page.screenshot({ path: '/tmp/pocket-dev-workspace-mobile.png' });
  await page.reload();
  await page.getByRole('button', { name: 'Open notes.txt', exact: true }).waitFor();
  assert.match(await content.textContent(), /Mobile draft/);
  await page.locator('.ws-mobile').getByRole('button', { name: 'Terminal', exact: true }).click();
  await page.getByRole('button', { name: 'Expand terminal panel', exact: true }).click();
  await page.getByRole('button', { name: 'Editor', exact: true }).click();
  await content.waitFor({ state: 'visible' });
  for (const size of [{ width: 320, height: 740 }, { width: 844, height: 390 }, { width: 768, height: 1024 }, { width: 1024, height: 768 }]) {
    await page.setViewportSize(size);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `workspace fits ${size.width} × ${size.height}`);
    await content.waitFor({ state: 'visible' });
  }
  assert.deepEqual(errors, []);
  console.log('Workspace browser checks passed: folder explorer, syntax editor, tabs, save/conflict handling, create file, real project terminal, Codex/Claude sessions, session reuse, mobile panels and reload restoration.');
} finally {
  await browser?.close();
  for (const fn of cleanup) await fn();
  fs.rmSync(temp, { recursive: true, force: true });
}
